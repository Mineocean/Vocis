def _detect_language() -> str:
    """检测系统语言：中文系统返回 zh，否则 en。"""
    override = os.getenv("UI_LANGUAGE", "").strip().lower()
    if override in ("zh", "en"):
        return override
    try:
        import ctypes
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        if lang_id == 2052 or (0x0400 <= lang_id < 0x0800):
            return "zh"
    except (AttributeError, OSError):
        pass
    return "en"


_language = _detect_language()


def current_language() -> str:
    return _language


def tr(key: str, **kwargs: Any) -> str:
    """返回 key 对应的本地化文本，支持 {placeholder} 格式化。"""
    table = _EN if _language == "en" else _ZH
    text = table.get(key) or _ZH.get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def reload_language():
    """根据环境变量重新检测语言（设置保存后调用）。"""
    global _language
    _language = _detect_language()
